// Builds <id>/public for each game from src/ and shared/. No dependencies; run with `node tools/build.mjs`.
import { readFileSync, writeFileSync, mkdirSync, cpSync, rmSync, existsSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const read = (p) => readFileSync(join(root, p), "utf8");
const games = JSON.parse(read("src/games.json"));
const page = read("src/page.html");
const top = read("src/core-top.js"), shell = read("src/core-shell.js");
const esc = (s) => s.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");

for (const [id, g] of Object.entries(games)) {
  const out = join(root, id, "public");
  for (const keep of ["media"]) if (!existsSync(join(out, keep))) mkdirSync(join(out, keep), { recursive: true });
  rmSync(join(out, "fonts"), { recursive: true, force: true });
  cpSync(join(root, "shared/fonts"), join(out, "fonts"), { recursive: true });
  cpSync(join(root, "src/style.css"), join(out, "style.css"));
  const script = [`const GAME_ID=${JSON.stringify(id)};`, top, read(`src/${id}.js`), shell].join("\n");
  const html = page
    .replaceAll("{{NAME}}", esc(g.name)).replaceAll("{{TAGLINE}}", esc(g.tagline))
    .replaceAll("{{ACCENT}}", g.accent).replaceAll("{{FOOT}}", esc(g.foot))
    .replace("{{SCRIPT}}", () => script);
  writeFileSync(join(out, "index.html"), html);
  const manifest = JSON.parse(read(`manifests/${id}.json`));
  writeFileSync(join(out, "playtest.json"), JSON.stringify(manifest, null, 2) + "\n");
  writeFileSync(join(root, id, "wrangler.jsonc"), `// Generated by tools/build.mjs. Static assets only; the playtest hub proxies to this Worker.
{
\t"$schema": "../node_modules/wrangler/config-schema.json",
\t"name": "${id}",
\t"compatibility_date": "2026-10-01",
\t"assets": { "directory": "./public" }
}
`);
  console.log(`built ${id}`);
}
